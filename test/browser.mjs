import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {mkdirSync} from "node:fs";
import path from "node:path";
const runtime=process.env.GEODAM_TEST_RUNTIME||process.cwd();
const require=createRequire(path.join(runtime,"package.json"));
const {chromium}=require("playwright");
const base=process.argv[2]||"http://127.0.0.1:8791";
const browser=await chromium.launch({headless:true,...(process.env.GEODAM_BROWSER_CHANNEL?{channel:process.env.GEODAM_BROWSER_CHANNEL}:{})});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:"fr-FR"});
const page=await context.newPage(),errors=[];
page.on("pageerror",e=>errors.push(e.stack||e.message));
mkdirSync(".test-output",{recursive:true});
try{
  await page.goto(base+"/?demo=1");
  await page.locator('[data-action="tutorial"]').waitFor();
  await page.evaluate(()=>{
    document.querySelector('[data-mode="map"]').click();
    document.querySelector('#nav a[href="#/about"]').click();
  });
  await page.locator("#legal").waitFor();
  await page.waitForTimeout(200);
  assert.equal(await page.locator("#legal").count(),1,"abandoned game startup must not overwrite navigation");
  await page.getByRole("link",{name:"Jouer",exact:true}).click();
  await page.locator('[data-action="tutorial"]').click();
  await page.locator("#ctr").click();
  assert.equal(await page.locator("#ok").isVisible(),true);
  await page.locator("#ok").click();
  await page.locator("#next").click();
  await page.locator(".bigscore").waitFor();
  assert.match(await page.locator(".rankline").textContent(),/entraînement/);
  await page.locator("#tohome").click();
  await page.locator('[data-action="practice"]').click();
  await page.locator("#ctr").click();
  await page.locator("#ok").click();
  await page.locator("#next").click();
  await page.locator("#hint").click();
  await page.locator("#ctr").click();
  await page.reload();
  await page.locator('[data-action="resume"]').click();
  await page.locator("#ok").waitFor({state:"visible"});
  assert.match(await page.locator("#rd").textContent(),/2/);
  assert.equal(await page.locator("#ok").isEnabled(),true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:".test-output/mobile-game.png",fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"mobile horizontal overflow");
  // Coordinate placement without pointer manipulation.
  await page.locator(".coordinates summary").click();
  await page.locator('input[name="lat"]').fill("48.5");
  await page.locator('input[name="lon"]').fill("2.2");
  await page.locator(".coordinates button").click();
  await page.locator("#ok").click();
  await page.locator("#next").click();
  await page.getByRole("link",{name:"Jouer",exact:true}).click();
  await page.locator('[data-action="practice"]').waitFor();
  // Tab widgets use roving focus.
  const tabs=page.locator('[role="tablist"]').first();
  assert.equal(await tabs.locator('button[tabindex="0"]').count(),1);
  await tabs.locator('button[tabindex="0"]').focus();
  await page.keyboard.press("ArrowRight");
  assert.equal(await tabs.locator('button[tabindex="0"]').count(),1);
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.reload();await page.locator('[data-action="practice"]').waitFor();
  await context.setOffline(true);
  await page.reload();
  await page.locator('[data-action="practice"]').click();
  await page.locator("#ctr").click();await page.locator("#ok").click();await page.locator("#next").click();
  assert.match(await page.locator("#connection").textContent(),/Hors connexion/);
  await context.setOffline(false);
  await page.getByRole("link",{name:"Jouer",exact:true}).click();
  await page.getByRole("link",{name:"À propos",exact:true}).click();
  await page.locator("#legal").waitFor();
  assert.equal(await page.locator("main h1").count(),1);
  await page.screenshot({path:".test-output/mobile-about.png",fullPage:true});
  assert.deepEqual(errors,[]);
  console.log("Browser checks passed: tutorial, mobile confirmation, resume with pending marker/hints, keyboard tabs, offline practice, legal headings.");
}finally{await browser.close();}
