import assert from "node:assert/strict";
import {createHmac,randomUUID} from "node:crypto";
import {readFileSync} from "node:fs";
import * as S from "../public/js/shared.js";
const base=process.argv[2]||"http://127.0.0.1:8791";
if(!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base))throw new Error("Local test server only");
const secret="geodam-test-secret-at-least-32-characters";
const post=async(path,body,headers={})=>{
 const r=await fetch(base+path,{method:"POST",headers:{"content-type":"application/json",...headers},body:JSON.stringify(body)});
 return {status:r.status,...await r.json()};
};
const sign=p=>{const b=Buffer.from(JSON.stringify(p)).toString("base64url");return b+"."+createHmac("sha256",secret).update(b).digest("base64url");};
const session=await post("/api/session",{mode:"mission"});
const data=JSON.parse(Buffer.from(session.token.split(".")[0],"base64url"));
const dams=JSON.parse(readFileSync(new URL("../public/data/dams.json",import.meta.url))),missing=JSON.parse(readFileSync(new URL("../public/data/missing.json",import.meta.url)));
const rounds=S.pickMissionRounds(dams,missing,data.seed),guesses=rounds.map(r=>r.src==="k"?[dams[r.i].la,dams[r.i].lo]:[48.5,2.2]);
const evidence=rounds.filter(r=>r.src==="m").map(r=>({id:missing[r.i].id,source:"https://example.org/source",accuracy_km:2,comment:"Test evidence"}));
const token=sign({...data,t:Date.now()-16000});
const body={token,guesses,evidence};
const concurrent=await Promise.all([post("/api/finish",body),post("/api/finish",body)]);
assert.ok(concurrent.some(r=>r.status===200));
assert.ok(concurrent.every(r=>r.status===200||r.status===409));
const done=await post("/api/finish",body),again=await post("/api/finish",body);
assert.equal(done.community.saved,again.community.saved);assert.equal(done.score,again.score);assert.equal(done.claim,again.claim);
const changed=structuredClone(body);changed.guesses[0]=[0,0];
assert.equal((await post("/api/finish",changed)).status,409);
const repeated=await post("/api/finish",{...body,token:sign({...data,id:randomUUID(),t:Date.now()-16000})});
assert.equal(repeated.community.saved,0);
const id=evidence[0].id;
assert.equal((await post("/api/admin/review",{dam_id:id,status:"accepted",lat:48.5,lon:2.2,reviewer:"test",note:"Checked test source"})).status,401);
const admin={"Authorization":"Bearer dev-admin-token"};
assert.equal((await post("/api/admin/review",{dam_id:id,status:"accepted",lat:48.5,lon:2.2,reviewer:"test",note:"Checked test source"},admin)).status,200);
assert.equal((await post("/api/mission/status",{token})).items.find(x=>x.id===id).status,"accepted");
const detail=await fetch(base+"/api/admin/detail?id="+id,{headers:admin}).then(r=>r.json());
assert.ok(detail.history.some(h=>h.status==="accepted"&&h.note==="Checked test source"));
assert.ok(detail.proposals.every(p=>!Object.hasOwn(p,"ip")));
const oversized=await post("/api/session",{mode:"map",padding:"x".repeat(20000)});assert.equal(oversized.status,413);
assert.equal((await post("/api/session",{mode:"map"},{"Origin":"https://untrusted.example"})).status,403);
const raw=await fetch(base+"/api/session",{method:"POST",body:"not json"});assert.equal(raw.status,415);
const wrongLocation=await post("/api/admin/review",{dam_id:id,status:"accepted",lat:-40,lon:130,reviewer:"test",note:"Different verified location"},admin);
assert.equal(wrongLocation.status,200);
